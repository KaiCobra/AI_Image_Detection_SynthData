#!/usr/bin/env bash
# ============================================================
# Download AI-GENERATED image datasets into data/ai/
# Run from the project root directory.
#
# Recommended starter combination (~3 GB, no registration needed):
#   CIFAKE (FAKE split)  — CC BY 4.0  (60 K images @ 32×32, upscaled)
#   DiffusionDB 10 K     — CC BY 4.0  (10 K images @ 512×512)
# ============================================================
set -euo pipefail

AI_DIR="data/ai"
mkdir -p "$AI_DIR"

echo "=== Downloading AI-Generated Image Datasets ==="

# ── 1. CIFAKE via HuggingFace (no registration, CC BY 4.0) ──────────────────
# 60 000 images generated by Stable Diffusion v1.4 at 32×32.
# We upscale to 256×256 for better composite quality.
echo "[1/2] CIFAKE — 60 K fake images (HuggingFace, no login required)..."
python3 - <<'PYEOF'
import sys
from pathlib import Path

out_dir = Path("data/ai/cifake")
done    = out_dir / ".done"
out_dir.mkdir(parents=True, exist_ok=True)

if done.exists():
    print("    CIFAKE already downloaded.")
    sys.exit(0)

try:
    from datasets import load_dataset
    from PIL import Image as PILImage

    # dragonintelligence mirror — no HuggingFace login needed
    print("    Loading dragonintelligence/CIFAKE-image-dataset ...")
    ds = load_dataset("dragonintelligence/CIFAKE-image-dataset", split="train")
    # label: 1 = FAKE (AI-generated), 0 = REAL
    fake_ds = ds.filter(lambda x: x["label"] == 1)

    saved = 0
    for i, sample in enumerate(fake_ds):
        img = sample["image"].convert("RGB").resize((256, 256), PILImage.BICUBIC)
        img.save(out_dir / f"cifake_{i:05d}.png")
        saved += 1
        if saved % 10000 == 0:
            print(f"    Saved {saved} CIFAKE images...")

    done.touch()
    print(f"    CIFAKE done: {saved} images in {out_dir}")

except Exception as e:
    print(f"    [ERROR] {e}")
    print()
    print("    Manual alternative (Kaggle):")
    print("      pip install kaggle")
    print("      # place ~/.kaggle/kaggle.json first")
    print("      kaggle datasets download -d birdy654/cifake-real-and-ai-generated-synthetic-images")
    print("      # Then move FAKE/ folder to data/ai/cifake/")
PYEOF

# ── 2. DiffusionDB 10 K via HuggingFace (no registration, CC BY 4.0) ─────────
# 10 000 Stable Diffusion v1.4 images at native 512×512 PNG.
echo "[2/2] DiffusionDB — 10 K images @ 512×512 (HuggingFace)..."
python3 - <<'PYEOF'
import sys
from pathlib import Path

out_dir = Path("data/ai/diffusiondb_10k")
done    = out_dir / ".done"
out_dir.mkdir(parents=True, exist_ok=True)

if done.exists():
    print("    DiffusionDB already downloaded.")
    sys.exit(0)

try:
    from datasets import load_dataset

    print("    Loading poloclub/diffusiondb large_random_10k ...")
    ds = load_dataset("poloclub/diffusiondb", "large_random_10k", split="train")

    saved = 0
    for i, sample in enumerate(ds):
        img = sample["image"].convert("RGB")
        img.save(out_dir / f"diffdb_{i:05d}.png")
        saved += 1
        if saved % 2000 == 0:
            print(f"    Saved {saved}/10000 DiffusionDB images...")

    done.touch()
    print(f"    DiffusionDB done: {saved} images in {out_dir}")

except Exception as e:
    print(f"    [ERROR] {e}")
    print()
    print("    DiffusionDB subsets: large_random_1k / large_random_5k / large_random_10k")
    print("    See: https://huggingface.co/datasets/poloclub/diffusiondb")
PYEOF

echo ""
echo "=== AI dataset download complete ==="
echo "Images are in: $AI_DIR"
echo ""
echo "Optional larger datasets:"
echo "  ArtiFact  (2.5M, Apache 2.0, ~120 GB):"
echo "    kaggle datasets download -d awsaf49/artifact-dataset"
echo ""
echo "  GenImage  (2.68M, CC BY-NC-SA 4.0, ~500 GB):"
echo "    git clone https://github.com/GenImage-Dataset/GenImage"
echo "    python download_genimage.py --destination ./data/ai/genimage"
echo ""
echo "Counts:"
find "$AI_DIR" -name "*.jpg" -o -name "*.jpeg" -o -name "*.png" | wc -l
